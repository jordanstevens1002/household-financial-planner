def table(
    name: str,
    data: str,
    columns: tuple[tuple[str, str, bool], ...],
    top: int,
    bottom: int,
    *,
    label: str,
    visible: bool | str = True,
) -> dict[str, Any]:
    primary_columns = {
        key: {
            "index": index,
            "width": 150,
            "originalId": key,
            "id": key,
            "alias": key,
            "horizontalAlignment": "LEFT",
            "verticalAlignment": "CENTER",
            "columnType": "text",
            "textSize": "PARAGRAPH",
            "enableFilter": True,
            "enableSort": True,
            "isVisible": visible,
            "isDisabled": False,
            "isCellVisible": True,
            "isDerived": False,
            "label": label,
            "computedValue": (
                f'{{{{({name}.tableData || []).map((currentRow) => currentRow["{key}"])}}}}'
            ),
        }
        for index, (key, label, visible) in enumerate(columns)
    }
    return {
        "widgetName": name,
        "displayName": "Table",
        "type": "TABLE_WIDGET_V2",
        "widgetId": name.lower(),
        "parentId": "0",
        "topRow": top,
        "bottomRow": bottom,
        "leftColumn": 2,
        "rightColumn": 62,
        "tableData": data,
        "isVisible": visible,
        "isLoading": False,
        "renderMode": "CANVAS",
        "version": 3,
        "defaultPageSize": 0,
        "isVisibleDownload": True,
        "isVisibleFilters": True,
        "isVisibleSearch": True,
        "isVisiblePagination": True,
        "label": label,
        "searchKey": "",
        "columnOrder": [key for key, _, _ in columns],
        "primaryColumns": primary_columns,
        "derivedColumns": {},
        "columnSizeMap": {},
        "dynamicBindingPathList": [
            {"key": "tableData"},
            *([{"key": "isVisible"}] if isinstance(visible, str) else []),
            *[{"key": f"primaryColumns.{key}.computedValue"} for key, _, _ in columns],
        ],
        "dynamicTriggerPathList": [],
    }


def common_widgets(page_name: str) -> list[dict[str, Any]]:
    widgets = [
        text("PageTitle", page_name, 1, 6),
        text(
            "HouseholdContext",
            "{{appsmith.store.householdName || 'No household selected'}}",
            6,
            10,
        ),
    ]
    navigation_width = 64 // len(PAGES)
    for index, (name, _) in enumerate(PAGES):
        widgets.append(
            button(
                f"Nav{name.replace(' ', '')}",
                name,
                f"{{{{navigateTo('{name}', {{}}, 'SAME_WINDOW')}}}}",
                11,
                index * navigation_width,
                (index + 1) * navigation_width,
                disabled=(
                    "{{!appsmith.store.personId}}"
                    if name == "Person finances"
                    else "{{!appsmith.store.householdId}}"
                    if name in {"Cash flow", "Properties", "Retirement", "Timeline", "Scenarios"}
                    else False
                ),
            )
        )
    return widgets


